"""FUTURE bounded header generation from two existing user files.

No image extraction/conversion, raw analysis dump, download, Git or asset copy.
The audio metadata's link to the user's original conversion is an explicit
user-input premise; validating its schema does not prove that provenance.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
from code_elf import ELF, BOOT_SHA, dispatch
from audio_prepare import write_catalog

ROOT = Path(__file__).resolve().parents[1]

def user_file(name: str, maximum: int) -> Path:
    p = PurePosixPath(name.replace('\\','/'))
    if p.is_absolute() or ':' in name or any(x.lower() in ('..','external','.git') or x.lower().endswith('.iso') for x in p.parts):
        raise ValueError('Pass a local existing BOOT/metadata file, never an image or traversal path')
    target = ROOT.joinpath(*p.parts)
    for current in (target, *target.parents):
        if current == ROOT.parent:
            break
        if current.is_symlink() or (hasattr(current,'is_junction') and current.is_junction()):
            raise ValueError('Reparse user input')
    if not target.resolve().is_relative_to(ROOT) or not target.is_file() or not 0 < target.stat().st_size <= maximum:
        raise ValueError('Missing/out-of-bounds local user file')
    return target

def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--boot',required=True)
    p.add_argument('--audio-manifest',required=True)
    args = p.parse_args()
    boot = user_file(args.boot,1341110)
    metadata = user_file(args.audio_manifest,2*1024*1024)
    boot_bytes = boot.read_bytes()
    if len(boot_bytes)!=1341110 or hashlib.sha256(boot_bytes).hexdigest()!=BOOT_SHA:
        raise ValueError('Original BOOT identity mismatch')
    metadata_bytes=metadata.read_bytes()
    manifest = json.loads(metadata_bytes.decode('utf-8-sig'))
    if manifest.get('schema_version')!=1 or manifest.get('iso_sha256')!='c78d0974f660cd92c1b10a1466ac278625d38e4dd93bfb48f66f090ff7a4c119':
        raise ValueError('Expected existing audio_prepare manifest schema/original identity')
    clips=manifest.get('clips')
    if not isinstance(clips,list) or not 0 < len(clips) <= 1024:
        raise ValueError('Nonempty bounded original audio clip metadata required')
    ids=set()
    for c in clips:
        if not isinstance(c,dict) or not re.fullmatch(r'[A-Za-z0-9_]+',c.get('id','')) or c['id'] in ids:
            raise ValueError('Invalid/duplicate clip ID')
        ids.add(c['id'])
        if not re.fullmatch(r'assets/native/audio/pcm/[A-Za-z0-9_]+\.wav',c.get('path','')):
            raise ValueError('Unexpected PCM path')
        for name in ('frames','sample_rate','channels','loop_start','loop_end'):
            if type(c.get(name)) is not int:
                raise ValueError('Integer clip metadata required')
        if not 0 <= c['frames'] < 2**63 or not 1 <= c['sample_rate'] <= 384000 or c['channels'] not in (1,2):
            raise ValueError('Clip width/rate/channel outside supported domain')
        if not all(-1 <= c[n] <= c['frames'] for n in ('loop_start','loop_end')):
            raise ValueError('Loop bound outside clip')
    elf=ELF(boot)
    if elf.blob != boot_bytes:
        raise ValueError('BOOT changed during load')
    tables=[('ksc_handler_va',dispatch(elf,0xE01B8,254,0x6B9A4,'ksc_opcode')),
            ('ksc_builtin_handler_va',dispatch(elf,0xDFD58,241,0x68574,'ksc_builtin_via_8B'))]
    lines=['#pragma once','#include <array>','#include <cstdint>','',
           '// Generated by tools/code_elf.py from original BOOT; diagnostic addresses only.',
           '// No opcode semantics or CPU runtime is supplied by these tables.',
           'namespace dokodemo::recovered {']
    for variable,table in tables:
        entries=table['entries']
        lines.append(f'inline constexpr std::array<std::uint32_t, {len(entries)}> {variable} = {{')
        for start in range(0,len(entries),8):
            lines.append('    '+', '.join(f'0x{row["handler_va"]:08X}u' for row in entries[start:start+8])+',')
        lines.append('};')
    lines.extend(['} // namespace dokodemo::recovered',''])
    if boot.read_bytes()!=boot_bytes or metadata.read_bytes()!=metadata_bytes:
        raise ValueError('User input changed before header generation')
    dispatch_header=ROOT/'src/recovered/ksc_dispatch_addresses.h'
    dispatch_header.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
    write_catalog(clips)
    print(json.dumps({'status':'generated_from_explicit_user_inputs','headers':[
        'src/recovered/ksc_dispatch_addresses.h','src/audio_catalog.h'],
        'boot_sha256':BOOT_SHA,'audio_manifest_sha256':hashlib.sha256(metadata_bytes).hexdigest(),
        'audio_provenance':'user_input_premise_not_verified_original_conversion','full_game':False}))

if __name__=='__main__':
    main()
